def insert_markdown(path: Path, article_id: str, addition: str) -> None:
    text = path.read_text(encoding="utf-8")
    marker = f"<!-- {STAMP}:{article_id} -->"
    if marker in text:
        return
    needle = "\n## まとめ\n"
    if needle not in text:
        raise RuntimeError(f"Summary heading not found in {path}")
    block = f"\n{marker}\n\n{addition.rstrip()}\n"
    path.write_text(text.replace(needle, block + needle, 1), encoding="utf-8")


def insert_preview(path: Path, article_id: str, addition: str) -> None:
    text = path.read_text(encoding="utf-8")
    marker = f"<!-- {STAMP}:{article_id} -->"
    if marker in text:
        return
    match = re.search(r"<h2(?:\s[^>]*)?>\s*まとめ\s*</h2>", text)
    if not match:
        raise RuntimeError(f"Summary h2 not found in {path}")
    block = f"\n{marker}\n{addition.rstrip()}\n"
    path.write_text(text[: match.start()] + block + text[match.start() :], encoding="utf-8")


def update_registry_counts(path: Path, counts: dict[str, int]) -> None:
    text = path.read_text(encoding="utf-8")
    ids = re.findall(r'"article_id"\s*:\s*"(B\d{3})"', text)
    for article_id in ids:
        if article_id not in counts:
            continue
        start = text.index(f'"article_id": "{article_id}"')
        next_match = re.search(r'\n\s*\{\n\s*"[^\n]*"article_id"|\n\s*\{\n\s*"article_id"', text[start + 1 :])
        end = len(text) if next_match is None else start + 1 + next_match.start()
        segment = text[start:end]
        count = counts[article_id]
        if '"body_char_count_approx"' in segment:
            segment = re.sub(
                r'"body_char_count_approx"\s*:\s*\d+',
                f'"body_char_count_approx": {count}',
                segment,
                count=1,
            )
        else:
            line_end = segment.index("\n") + 1
            indent_match = re.search(r'(?m)^(\s*)"article_id"', segment)
            indent = indent_match.group(1) if indent_match else "      "
            segment = segment[:line_end] + f'{indent}"body_char_count_approx": {count},\n' + segment[line_end:]
        text = text[:start] + segment + text[end:]
    text = re.sub(
        r'"updated_at"\s*:\s*"[^"]+"',
        '"updated_at": "2026-09-07T20:10:00+09:00"',
        text,
        count=1,
    )
    path.write_text(text, encoding="utf-8")


def append_checklist_metric(article_id: str, count: int, minimum: int | None, status: str) -> None:
    path = ROOT / "docs" / "reviews" / f"{article_id}_CHECKLIST.md"
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    marker = f"<!-- {STAMP}:metric -->"
    if marker in text:
        text = re.sub(
            rf"{re.escape(marker)}.*?<!-- /{re.escape(STAMP)}:metric -->",
            "",
            text,
            flags=re.DOTALL,
        ).rstrip() + "\n"
    min_text = "数値基準なし" if minimum is None else f"{minimum:,}字"
    block = (
        f"\n{marker}\n"
        "## 2026-09-07 本文量・読者満足度の再確認\n\n"
        f"- reader_visible_char_count: **{count:,}字**\n"
        f"- guideline_minimum: **{min_text}**\n"
        f"- length_status: **{status}**\n"
        "- counting_method: frontmatter・URL・Markdown記号・公的情報/出典一覧を除き、読者が読む本文の非空白文字を同一スクリプトで計測。\n"
        "- editorial_note: 文字数そのものではなく、判断条件・具体例・生活への置き換え・次の行動の充足を優先して再確認。\n"
        f"<!-- /{STAMP}:metric -->\n"
    )
    path.write_text(text.rstrip() + "\n" + block, encoding="utf-8")


def write_report(rows) -> None:
    path = ROOT / "docs" / "reviews" / "ARTICLE_CONTENT_METRICS_20260907.md"
    failures = [row for row in rows if row.length_status == "FAIL_LENGTH"]
    summary = (
        "# B001〜B058 本文文字数・内容深度監査\n\n"
        "- audit_date: 2026-09-07\n"
        "- scope: B001〜B058\n"
        "- counting: frontmatter・URL・Markdown記号・公的情報/出典一覧を除いた読者本文の非空白文字\n"
        "- quality_rule: 文字数だけでなく読者の納得度・具体例・次の行動を最終基準とする\n\n"
        f"- numeric_failures: {len(failures)}\n\n"
        + markdown(rows)
        + "\n"
    )
    path.write_text(summary, encoding="utf-8")


def main() -> int:
    for article_id, fix in FIXES.items():
        insert_markdown(ROOT / fix["source"], article_id, fix["md"])
        insert_preview(ROOT / fix["preview"], article_id, fix["html"])

    rows = audit()
    counts = {row.article_id: row.body_char_count for row in rows}
    update_registry_counts(ROOT / "data" / "content_registry.json", counts)
    update_registry_counts(ROOT / "data" / "content_registry_additions.json", counts)

    for row in rows:
        append_checklist_metric(
            row.article_id,
            row.body_char_count,
            row.minimum_char_count,
            row.length_status,
        )
    write_report(rows)

    failures = [row for row in rows if row.length_status == "FAIL_LENGTH"]
    print(markdown(rows))
    if failures:
        print("FAIL_LENGTH: " + ", ".join(row.article_id for row in failures))
        return 1
    return 0


